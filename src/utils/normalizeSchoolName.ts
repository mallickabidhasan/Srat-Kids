/**
 * Normalizes any school name string to its canonical official name.
 */
export function normalizeSchoolName(rawName?: string | null): string {
  if (!rawName) return '';
  const trimmed = rawName.trim();
  if (EXACT_SCHOOL_NAME_MAP[trimmed]) {
    return EXACT_SCHOOL_NAME_MAP[trimmed];
  }

  // Normalize multiple spaces and check again
  const singleSpaced = trimmed.replace(/\s+/g, ' ');
  if (EXACT_SCHOOL_NAME_MAP[singleSpaced]) {
    return EXACT_SCHOOL_NAME_MAP[singleSpaced];
  }

  return singleSpaced;
}
