// Helper to convert Bengali numbers to English digits and vice-versa
export function normalizeNumberString(str: string): string {
  const bnToEnMap: Record<string, string> = {
    '০': '0', '১': '1', '২': '2', '৩': '3', '৪': '4',
    '৫': '5', '৬': '6', '৭': '7', '৮': '8', '৯': '9',
  };
  return str.replace(/[০-৯]/g, (match) => bnToEnMap[match] || match).trim();
}

export function toBengaliNumber(num: number | string): string {
  const enToBnMap: Record<string, string> = {
    '0': '০', '1': '১', '2': '২', '3': '৩', '4': '৪',
    '5': '৫', '6': '৬', '7': '৭', '8': '৮', '9': '৯',
  };
  return String(num).replace(/[0-9]/g, (match) => enToBnMap[match] || match);
}

export interface SearchFilterOptions {
  query?: string;
  codeNumber?: string;
  studentName?: string;
  schoolName?: string;
  className?: string; // 'all' | 'দশম' | 'নবম' | 'অষ্টম' | 'সপ্তম' | 'ষষ্ঠ' | 'পঞ্চম' | 'চতুর্থ' | 'তৃতীয়' | 'দ্বিতীয়' | 'প্রথম' | 'কেজি'
  scholarshipType?: 'all' | 'ট্যালেন্টপুল' | 'সাধারণ';
}

export function searchScholarshipResults(options: SearchFilterOptions): ScholarshipStudentResult[] {
  const rawQuery = options.query?.trim() || '';
  const normalizedQuery = normalizeNumberString(rawQuery).toLowerCase();

  const codeQuery = normalizeNumberString(options.codeNumber?.trim() || '').toLowerCase();
  const nameQuery = (options.studentName?.trim() || '').toLowerCase();
  const schoolQuery = (options.schoolName?.trim() || '').toLowerCase();
  const normalizedSchoolQuery = normalizeSchoolName(options.schoolName || '').toLowerCase();
  const classFilter = (options.className?.trim() || '').toLowerCase();
  const typeFilter = options.scholarshipType || 'all';

  return ALL_SCHOLARSHIP_RESULTS_2026.filter((student) => {
    // 1. Filter by specific class if selected
    if (classFilter && classFilter !== 'all') {
      const matchTenth = (classFilter.includes('দশম') || classFilter.includes('১০ম') || classFilter.includes('10')) && student.className === 'দশম';
      const matchNinth = (classFilter.includes('নবম') || classFilter.includes('৯ম') || classFilter.includes('9')) && student.className === 'নবম';
      const matchEighth = (classFilter.includes('অষ্টম') || classFilter.includes('৮ম') || classFilter.includes('8')) && student.className === 'অষ্টম';
      const matchSeventh = (classFilter.includes('সপ্তম') || classFilter.includes('৭ম') || classFilter.includes('7')) && student.className === 'সপ্তম';
      const matchSixth = (classFilter.includes('ষষ্ঠ') || classFilter.includes('৬ষ্ঠ') || classFilter.includes('6')) && student.className === 'ষষ্ঠ';
      const matchFifth = (classFilter.includes('পঞ্চম') || classFilter.includes('৫ম') || classFilter.includes('5')) && student.className === 'পঞ্চম';
      const matchFourth = (classFilter.includes('চতুর্থ') || classFilter.includes('৪র্থ') || classFilter.includes('4')) && student.className === 'চতুর্থ';
      const matchThird = (classFilter.includes('তৃতীয়') || classFilter.includes('৩য়') || classFilter.includes('৩য়') || classFilter.includes('3')) && student.className === 'তৃতীয়';
      const matchSecond = (classFilter.includes('দ্বিতীয়') || classFilter.includes('২য়') || classFilter.includes('২য়') || classFilter.includes('2')) && student.className === 'দ্বিতীয়';
      const matchFirst = (classFilter.includes('প্রথম') || classFilter.includes('১ম') || classFilter.includes('1')) && student.className === 'প্রথম';
      const matchKg = (classFilter.includes('কেজি') || classFilter.includes('kg')) && student.className === 'কেজি';
      if (!matchTenth && !matchNinth && !matchEighth && !matchSeventh && !matchSixth && !matchFifth && !matchFourth && !matchThird && !matchSecond && !matchFirst && !matchKg) {
        return false;
      }
    }

    // 2. Filter by scholarship type if specified
    if (typeFilter !== 'all' && student.scholarshipType !== typeFilter) {
      return false;
    }

    // 3. Filter by specific school if provided
    if (schoolQuery && schoolQuery !== 'all') {
      const studentSchoolNorm = normalizeSchoolName(student.schoolName).toLowerCase();
      if (!studentSchoolNorm.includes(normalizedSchoolQuery) && !student.schoolName.toLowerCase().includes(schoolQuery)) {
        return false;
      }
    }

    // 4. Filter by specific name if provided
    if (nameQuery && !student.studentNameBn.toLowerCase().includes(nameQuery)) {
      return false;
    }

    // 5. Filter by specific code if provided
    if (codeQuery && student.codeNumber !== codeQuery && normalizeNumberString(student.codeNumber) !== codeQuery) {
      return false;
    }

    // 6. Global query matching: if provided, check ANY of codeNumber, studentName, schoolName, className, scholarshipType
    if (rawQuery) {
      const matchCode = student.codeNumber === normalizedQuery ||
        toBengaliNumber(student.codeNumber) === rawQuery ||
        student.codeNumber.toLowerCase().includes(normalizedQuery);
      
      const matchName = student.studentNameBn.toLowerCase().includes(rawQuery.toLowerCase());
      const matchSchool = student.schoolName.toLowerCase().includes(rawQuery.toLowerCase()) ||
        normalizeSchoolName(student.schoolName).toLowerCase().includes(rawQuery.toLowerCase());
      
      const matchClass = 
        ((rawQuery.includes('দশম') || rawQuery.includes('১০ম') || normalizedQuery === '10') && student.className === 'দশম') ||
        ((rawQuery.includes('নবম') || rawQuery.includes('৯ম') || normalizedQuery === '9') && student.className === 'নবম') ||
        ((rawQuery.includes('অষ্টম') || rawQuery.includes('৮ম') || normalizedQuery === '8') && student.className === 'অষ্টম') ||
        ((rawQuery.includes('সপ্তম') || rawQuery.includes('৭ম') || normalizedQuery === '7') && student.className === 'সপ্তম') ||
        ((rawQuery.includes('ষষ্ঠ') || rawQuery.includes('৬ষ্ঠ') || normalizedQuery === '6') && student.className === 'ষষ্ঠ') ||
        ((rawQuery.includes('পঞ্চম') || rawQuery.includes('৫ম') || normalizedQuery === '5') && student.className === 'পঞ্চম') ||
        ((rawQuery.includes('চতুর্থ') || rawQuery.includes('৪র্থ') || normalizedQuery === '4') && student.className === 'চতুর্থ') ||
        ((rawQuery.includes('তৃতীয়') || rawQuery.includes('৩য়') || rawQuery.includes('৩য়') || normalizedQuery === '3') && student.className === 'তৃতীয়') ||
        ((rawQuery.includes('দ্বিতীয়') || rawQuery.includes('২য়') || rawQuery.includes('২য়') || normalizedQuery === '2') && student.className === 'দ্বিতীয়') ||
        ((rawQuery.includes('প্রথম') || rawQuery.includes('১ম') || normalizedQuery === '1') && student.className === 'প্রথম') ||
        ((rawQuery.includes('কেজি') || rawQuery.toLowerCase().includes('kg')) && student.className === 'কেজি');
      
      const matchType = student.scholarshipType.includes(rawQuery) || student.categoryGrade.toLowerCase().includes(rawQuery.toLowerCase());

      if (!matchCode && !matchName && !matchSchool && !matchClass && !matchType) {
        return false;
      }
    }

    return true;
  });
}

